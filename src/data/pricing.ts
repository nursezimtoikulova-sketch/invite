/** Подпись цены на карточке тарифа */
export const planPriceLabel = (plan: PricingPlan, lang: Lang): string => {
  if (plan.price === null) return lang === 'kg' ? 'сурам боюнча' : 'по запросу';
  const n = formatPrice(plan.price);
  return lang === 'kg' ? `${n} сомдон` : `от ${n} сом`;
};

